#!/usr/bin/env node
/**
 * Regenerates src/lib/theme/scaleBaseline.ts from the CURRENT per-file counts.
 *
 *   node scripts/generate-scale-baseline.mjs
 *
 * Run it after a slice shrinks a file — never hand-edit the baseline. The
 * ratchet (src/lib/theme/scaleRatchet.test.ts) fails BOTH ways: a count that
 * grows is a regression, and a count that shrank without being recorded here is
 * an unbanked win that could silently come back. Regenerating is how a win gets
 * banked.
 *
 * Scope, patterns and counting live in src/lib/theme/scaleScan.ts — the same
 * module the test imports, so the two cannot drift. Node runs the .ts import
 * directly (native type stripping).
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { countScaleOffenders, SCALE_KINDS } from '../src/lib/theme/scaleScan.ts'

/** Walk src/ for the same set SCALE_SCOPE_GLOB matches in the test. */
function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) {
      yield* walk(path)
      continue
    }
    if (name.endsWith('.svelte') || path === 'src/app.css') yield path
  }
}

const rows = []
const totals = { emFont: 0, offScaleFont: 0, offScaleSpace: 0, offScaleWeight: 0 }
let files = 0
let dirty = 0

for (const file of [...walk('src')].sort()) {
  files += 1
  const counts = countScaleOffenders(readFileSync(file, 'utf8'))
  for (const kind of SCALE_KINDS) totals[kind] += counts[kind]
  if (SCALE_KINDS.some((kind) => counts[kind] > 0)) {
    dirty += 1
    rows.push(
      `  '${file}': { emFont: ${counts.emFont}, offScaleFont: ${counts.offScaleFont},` +
        ` offScaleSpace: ${counts.offScaleSpace}, offScaleWeight: ${counts.offScaleWeight} },`,
    )
  }
}

writeFileSync(
  'src/lib/theme/scaleBaseline.ts',
  `// GENERATED by scripts/generate-scale-baseline.mjs — DO NOT HAND-EDIT.
//
// The per-file CEILING of off-scale type and spacing decisions
// (docs/design/ui-refactor-plan.md, Batch 2D; audit F6 + F7). Files that are
// fully on the scale are omitted, so an entry disappearing is a file finished.
//
// src/lib/theme/scaleRatchet.test.ts fails when any count GROWS and when a
// shrink is not recorded here. Regenerate to record a shrink:
//   node scripts/generate-scale-baseline.mjs
import type { ScaleCounts } from './scaleScan'

export const SCALE_BASELINE: Record<string, ScaleCounts> = {
${rows.join('\n')}
}
`,
)

console.log(
  `scaleBaseline: ${files} files scanned, ${dirty} off the scale — ` +
    `emFont ${totals.emFont}, offScaleFont ${totals.offScaleFont}, ` +
    `offScaleSpace ${totals.offScaleSpace}, offScaleWeight ${totals.offScaleWeight}`,
)
